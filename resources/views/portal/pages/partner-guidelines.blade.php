<section id="roles" class="guidelines-section">
    <div class="container">
        <div class="section-header-left">
            <div class="section-icon">
                <i class="bi bi-people"></i>
            </div>
            <div>
                <h2 class="section-title">Ways to Join</h2>
                <p class="section-subtitle">Three roles — hold one, or hold several</p>
            </div>
        </div>

        <div class="guidelines-content">
            <div class="guideline-card">
                <h3>Heco Local Host (HLH)</h3>
                <ul>
                    <li>
                        <strong>You host travellers.</strong> Homestays, lodges and the
                        experiences built around them — a place to stay, and the life that
                        goes with it.
                    </li>
                    <li>
                        <strong>You author experiences.</strong> Guided cultural and outdoor
                        activities, workshops, handicrafts, local knowledge and storytelling.
                    </li>
                    <li>
                        <strong>You do not need a registered business.</strong> Many of our
                        hosts are individuals and families. If there is no company, your own
                        name is the name we know you by.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Other Service Provider (OSP)</h3>
                <ul>
                    <li>
                        <strong>You supply services into journeys.</strong> Standard
                        accommodation, taxi and transport, guiding, equipment rental, and
                        anything else a traveller needs on the ground.
                    </li>
                    <li>
                        <strong>You keep a rate card</strong> rather than a catalogue of
                        experiences — your prices, per service, kept current by you.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Heco Regional Partner (HRP)</h3>
                <ul>
                    <li>
                        <strong>You coordinate a region.</strong> A regional partner does not
                        sell a catalogue; they hold the local relationships and help hosts and
                        suppliers in their area work together.
                    </li>
                    <li>
                        <strong>Your application is judged differently.</strong> Because there
                        is nothing to list, we ask instead about your background — education,
                        languages, computer skills, work experience, and the causes and
                        communities you are close to.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Holding More Than One Role</h3>
                <ul>
                    <li>
                        <strong>Pick every role that fits you.</strong> A host who also runs a
                        taxi is an HLH and an OSP; a regional partner who hosts is an HRP and
                        an HLH. Any combination is fine.
                    </li>
                    <li>
                        <strong>You are only asked what applies.</strong> Each role brings its
                        own questions at signup, and nothing is stored against a role you did
                        not choose.
                    </li>
                </ul>
            </div>
        </div>
    </div>
</section>

