<section id="joining" class="guidelines-section">
    <div class="container">
        <div class="section-header-left">
            <div class="section-icon">
                <i class="bi bi-clipboard-check"></i>
            </div>
            <div>
                <h2 class="section-title">The Application</h2>
                <p class="section-subtitle">From applying to taking your first booking</p>
            </div>
        </div>

        <div class="guidelines-content">
            <div class="guideline-card">
                <h3>How It Works</h3>
                <ul>
                    <li>
                        <strong>You apply</strong> from this site or the HECO Provider app,
                        choosing your password as you go. You will get a confirmation email
                        straight away.
                    </li>
                    <li>
                        <strong>Our team reviews it.</strong> Until then your account is open
                        but your listing is not live, and you will see your application status
                        when you sign in.
                    </li>
                    <li>
                        <strong>We email you the decision.</strong> Once approved you can sign
                        in properly, complete your profile, and start taking bookings.
                    </li>
                    <li>
                        <strong>If we cannot approve you,</strong> we will say so and you are
                        welcome to contact us for the reasons or to apply again.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>What To Have Ready</h3>
                <ul>
                    <li>
                        <strong>How to reach you</strong> — a contact name, phone number and
                        email, and whether you would rather hear from us by email or WhatsApp.
                        Many of our members do not check email often, so tell us what suits you.
                    </li>
                    <li>
                        <strong>Where you are</strong> — the region you operate in, and your
                        address.
                    </li>
                    <li>
                        <strong>Languages you speak</strong> — this helps us match you with
                        travellers you can host comfortably.
                    </li>
                    <li>
                        <strong>Verification documents</strong> — identity or business papers,
                        as JPG, PNG or PDF, up to 2&nbsp;MB each. A profile photo is welcome too.
                    </li>
                    <li>
                        <strong>Business details, if you have a business.</strong> If you do
                        not, skip it — it is not a requirement.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Your Account</h3>
                <ul>
                    <li>
                        <strong>One application per email address.</strong> If you already
                        travel with HECO on that address, that stays your traveller account —
                        your partner account is separate.
                    </li>
                    <li>
                        <strong>Keep your own details current.</strong> You can edit your
                        profile, contact details and bank details yourself at any time.
                    </li>
                    <li>
                        <strong>If your account shows as out of service,</strong> your listings
                        are paused and you will not receive new bookings. Contact us and we
                        will talk it through.
                    </li>
                </ul>
            </div>
        </div>
    </div>
</section>

