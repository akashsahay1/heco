            </div>
        </div>

        <div class="guidelines-content">
            <div class="guideline-card">
                <h3>Publishing</h3>
                <ul>
                    <li>
                        <strong>Everything you publish is reviewed.</strong> New experiences
                        and rates go to our team before they reach travellers, and so do later
                        edits — your live version keeps selling until the change is approved.
                    </li>
                    <li>
                        <strong>Save a draft whenever you like.</strong> You do not need every
                        detail and photo in one sitting; a draft is never submitted for review
                        until you say so.
                    </li>
                    <li>
                        <strong>There is a limit on how many experiences you may list.</strong>
                        The app shows how much room you have left. If you genuinely need more,
                        ask us.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Staying Bookable</h3>
                <ul>
                    <li>
                        <strong>Keep your availability current.</strong> Block the dates you
                        cannot take, and release them when you can. If you already keep a
                        calendar elsewhere, you can sync it in.
                    </li>
                    <li>
                        <strong>Answer booking requests promptly.</strong> A traveller is
                        usually holding a whole itinerary together around your answer.
                    </li>
                    <li>
                        <strong>Describe honestly what you offer.</strong> Photos and
                        descriptions should be your own and should match what a traveller will
                        actually find when they arrive.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Pricing And Payment</h3>
                <ul>
                    <li>
                        <strong>Your rates are yours to set</strong> and yours to keep current.
                        Travellers see a price built from them.
                    </li>
                    <li>
                        <strong>Give us your bank or UPI details</strong> in your profile so
