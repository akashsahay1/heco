    <div class="container">
        <div class="section-header-left">
            <div class="section-icon">
                <i class="bi bi-heart"></i>
            </div>
            <div>
                <h2 class="section-title">What We Ask Of You</h2>
                <p class="section-subtitle">The values every HECO partner shares</p>
            </div>
        </div>

        <div class="guidelines-content">
            <div class="guideline-card">
                <h3>Regenerative By Default</h3>
                <ul>
                    <li>
                        <strong>Leave your place better than you found it.</strong> We go
                        beyond sustainability — restoration and conservation belong inside the
                        experience, not alongside it.
                    </li>
                    <li>
                        <strong>Tread lightly.</strong> Avoid single-use plastic, manage waste
                        properly, and keep your operation as low-impact as your setting allows.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Community First</h3>
                <ul>
                    <li>
                        <strong>Local people design the experience.</strong> You set the pace
                        and share what is genuinely yours to share.
                    </li>
                    <li>
                        <strong>Buy and hire locally</strong> wherever you can, so what
                        travellers spend stays in the region.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Authenticity And Transparency</h3>
                <ul>
                    <li>
                        <strong>No staged performances.</strong> Every meal, story and
                        interaction should be the real thing.
                    </li>
                    <li>
                        <strong>Be straight about your pricing</strong> and about what is and
                        is not included, so travellers know exactly what they are paying for.
                    </li>
                    <li>
                        <strong>Respect travellers' privacy</strong> and treat every guest with
                        the same courtesy, whoever they are.
                    </li>
                </ul>
            </div>

            <div class="guideline-card">
                <h3>Getting Help</h3>
                <ul>
                    <li>
                        <strong>Ask us.</strong> If something is unclear, or you are unsure
                        whether something belongs on HECO, contact the team before you publish
                        it — <a href="{{ route('contact') }}">get in touch</a>.
                    </li>
                    <li>
                        <strong>These guidelines sit alongside our</strong>
                        <a href="{{ route('terms') }}">Terms &amp; Conditions</a> and
                        <a href="{{ route('privacy') }}">Privacy Policy</a>.
                    </li>
                </ul>
            </div>
